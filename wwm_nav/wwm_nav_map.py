def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def semantic_npz_sha256(path: Path) -> str:
    """Hash NPZ array contents without depending on ZIP timestamps."""

    digest = hashlib.sha256()
    with np.load(path, allow_pickle=False) as data:
        for name in sorted(data.files):
            value = np.ascontiguousarray(np.asarray(data[name]))
            digest.update(name.encode("utf-8"))
            digest.update(b"\0")
            digest.update(value.dtype.str.encode("ascii"))
            digest.update(b"\0")
            digest.update(json.dumps(value.shape).encode("ascii"))
            digest.update(b"\0")
            digest.update(value.tobytes(order="C"))
    return digest.hexdigest()


def array_content_sha256(value: np.ndarray) -> str:
    return hashlib.sha256(np.ascontiguousarray(value).tobytes(order="C")).hexdigest()


def reconstruct_wwm_nav_height_map(seed: int = WWM_NAV_GENERATION_SEED) -> np.ndarray:
    """Recreate the city generated by the registered WWM-NAV radio environment."""

    alpha = 0.3
    beta = 300
    gamma = 50.0
    max_height_m = 90.0
    area_km = 2
    cluster_per_side = 3
    road_width_km = 0.02
    step = 101
    total_buildings = beta * (area_km**2)
    rng = np.random.RandomState(int(seed))
    height_vec = np.minimum(rng.rayleigh(gamma, total_buildings), max_height_m)

    cluster_count = cluster_per_side**2
    buildings_per_cluster = [
        np.ceil(total_buildings / cluster_count) for _ in range(cluster_count)
    ]
    extra_building = int(np.sum(buildings_per_cluster) - total_buildings)
    if extra_building > 1:
        buildings_per_cluster[: extra_building - 1] = [
            np.ceil(total_buildings / cluster_count) - 1
            for _ in range(extra_building)
        ]

    cluster_size = (
        area_km - (cluster_per_side - 1) * road_width_km
    ) / cluster_per_side
    cluster_center = (
        np.arange(cluster_per_side) * (cluster_size + road_width_km)
        + cluster_size / 2.0
    )
    side_km = float(np.sqrt(alpha * (area_km**2) / total_buildings))
    x_locations: list[float] = []
    y_locations: list[float] = []
    for x_index in range(cluster_per_side):
        for y_index in range(cluster_per_side):
            cluster_index = x_index * cluster_per_side + y_index
            building_count = int(buildings_per_cluster[cluster_index])
            buildings_per_row = int(np.ceil(np.sqrt(building_count)))
            row_locations = np.linspace(
                (-cluster_size + 2.0 * side_km) / 2.0,
                (cluster_size - 2.0 * side_km) / 2.0,
                buildings_per_row,
            )
            x_locations.extend(
                list(
                    (
                        np.asarray(list(row_locations) * buildings_per_row)
                        + cluster_center[x_index]
                    )[:building_count]
                )
            )
            y_locations.extend(
                list(
                    (
                        np.repeat(list(row_locations), buildings_per_row)
                        + cluster_center[y_index]
                    )[:building_count]
                )
            )

    height_map = np.zeros((area_km * step, area_km * step), dtype=np.float64)
    for building_index in range(total_buildings):
        x1 = x_locations[building_index] - side_km / 2.0
        x2 = x_locations[building_index] + side_km / 2.0
        y1 = y_locations[building_index] - side_km / 2.0
        y2 = y_locations[building_index] + side_km / 2.0
        height_map[
            int(np.ceil(x1 * step) - 1) : int(np.floor(x2 * step)),
            int(np.ceil(y1 * step) - 1) : int(np.floor(y2 * step)),
        ] = height_vec[building_index]
    return height_map


def _scalar(data: np.lib.npyio.NpzFile, field: str):
    return np.asarray(data[field]).reshape(-1)[0].item()


def validate_wwm_nav_generated_map(path: Path) -> None:
    """Validate a map emitted by the registered direct-generation command."""

    path = Path(path)
    with np.load(path, allow_pickle=False) as data:
        if set(data.files) != WWM_NAV_MAP_FIELDS:
            missing = sorted(WWM_NAV_MAP_FIELDS.difference(data.files))
            extra = sorted(set(data.files).difference(WWM_NAV_MAP_FIELDS))
            raise ValueError(
                f"WWM-NAV generated-map field set mismatch: missing={missing}, extra={extra}"
            )
        contract = str(_scalar(data, "wwm_nav_map_contract"))
        if contract != WWM_NAV_MAP_CONTRACT:
            raise ValueError("radiomap does not use the registered WWM-NAV generation contract")
        if int(_scalar(data, "generation_seed")) != WWM_NAV_GENERATION_SEED:
            raise ValueError("WWM-NAV radio-environment seed mismatch")
        if int(_scalar(data, "fast_fading_samples")) != WWM_NAV_FAST_FADING_SAMPLES:
            raise ValueError("WWM-NAV fast-fading sample count mismatch")
        if int(_scalar(data, "los_samples")) != WWM_NAV_LOS_SAMPLES:
            raise ValueError("WWM-NAV LoS sample count mismatch")

        outage = np.asarray(data["arr_0"], dtype=np.float64)
        x_axis = np.asarray(data["arr_1"])
        y_axis = np.asarray(data["arr_2"])
        test_locations = np.asarray(data["arr_3"], dtype=np.float64)
        test_outages = np.asarray(data["arr_4"], dtype=np.float64)
        if outage.shape != (201, 201):
            raise ValueError("registered WWM-NAV map must use the 201x201 grid")
        if not np.array_equal(x_axis, np.arange(201)) or not np.array_equal(
            y_axis, np.arange(201)
        ):
            raise ValueError("WWM-NAV map axes must be the registered 0..200 grid")
        if not np.all(np.isfinite(outage)) or np.any((outage < 0.0) | (outage > 1.0)):
            raise ValueError("WWM-NAV outage probabilities must be finite and in [0, 1]")
        if test_locations.shape != (4040, 2) or test_outages.shape != (4040,):
            raise ValueError("WWM-NAV generated test-set shape mismatch")
        if not np.all(np.isfinite(test_locations)) or not np.all(
            np.isfinite(test_outages)
        ):
            raise ValueError("WWM-NAV generated test set contains non-finite values")
        if np.any((test_outages < 0.0) | (test_outages > 1.0)):
            raise ValueError("WWM-NAV test outage probabilities must be in [0, 1]")

        for field, expected_hash in WWM_NAV_LEGACY_ARRAY_CONTENT_SHA256.items():
            actual_hash = array_content_sha256(np.asarray(data[field]))
            if actual_hash != expected_hash:
                raise ValueError(
                    f"WWM-NAV generated map does not reproduce the registered "
                    f"research-one {field} contents"
                )

        if not np.array_equal(np.asarray(data["bs_loc_km"]), WWM_NAV_BS_LOC_KM):
            raise ValueError("WWM-NAV base-station geometry mismatch")
        if not np.array_equal(
            np.asarray(data["sector_boresite_deg"]), WWM_NAV_SECTOR_BORESITE_DEG
        ):
            raise ValueError("WWM-NAV sector geometry mismatch")
        if not np.array_equal(
            np.asarray(data["height_map"]), reconstruct_wwm_nav_height_map()
        ):
            raise ValueError("WWM-NAV generated city height map mismatch")

        best_bs = np.asarray(data["best_bs"])
        best_sector = np.asarray(data["best_sector"])
        if best_bs.shape != outage.shape or np.any(
            (best_bs < 0) | (best_bs >= WWM_NAV_BS_LOC_KM.shape[0])
        ):
            raise ValueError("WWM-NAV best-BS labels are invalid")
        if best_sector.shape != outage.shape or np.any(
            (best_sector < 0) | (best_sector >= WWM_NAV_SECTOR_BORESITE_DEG.size)
        ):
            raise ValueError("WWM-NAV best-sector labels are invalid")

        expected_scalars = {
            "bs_power_watt": 0.1,
            "uav_height_km": 0.1,
            "max_height_m": 90.0,
            "bs_downtilt_deg": 100.0,
            "carrier_freq_ghz": 2.0,
        }
        for field, expected in expected_scalars.items():
            if _scalar(data, field) != expected:
                raise ValueError(f"WWM-NAV generated-map field mismatch: {field}")
